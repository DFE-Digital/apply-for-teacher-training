require 'rails_helper'

RSpec.describe DataMigrations::DeleteCandidatesGeneratedByGhostDatabaseIncident do
  describe '#change' do
    it 'deletes the candidates generated by the ghost database incident' do
      70.times do |i|
        create(:candidate, id: i + 1)
      end

      described_class.new.change

      (1..35).each do |i|
        expect { Candidate.find(i) }.to raise_error(ActiveRecord::RecordNotFound)
      end
      expect(Candidate.find(36)).to be_present
      (37..42).each do |i|
        expect { Candidate.find(i) }.to raise_error(ActiveRecord::RecordNotFound)
      end
      expect(Candidate.find(43)).to be_present
      expect { Candidate.find(44) }.to raise_error(ActiveRecord::RecordNotFound)
      expect(Candidate.find(45)).to be_present
      expect { Candidate.find(46) }.to raise_error(ActiveRecord::RecordNotFound)
      (47..70).each do |i|
        expect(Candidate.find(i)).to be_present
      end
    end
  end
end
